-- =====================================================================
-- ESN Awards — Supabase schema
-- Run once in the Supabase SQL editor (as the `postgres` role).
-- =====================================================================

-- Supabase runs in UTC. The "one vote per day" rule must reset at
-- midnight Ulaanbaatar time, so set the database default time zone.
-- (Takes effect for new connections.)
ALTER DATABASE postgres SET timezone TO 'Asia/Ulaanbaatar';

CREATE SCHEMA IF NOT EXISTS esn;

-- Keep the schema private: the app connects directly with `pg`, never
-- through the Supabase REST API, so the anon/authenticated roles get nothing.
REVOKE ALL ON SCHEMA esn FROM anon, authenticated;


-- ---------------------------------------------------------------------
-- Nominees (one row per nomination, filtered by slug + sport_id)
-- ---------------------------------------------------------------------
CREATE TABLE esn.awards (
    id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug                 varchar(32) NOT NULL,
    sport_id             int8,
    team_id              int8,
    team_name            varchar(255),
    team_image_url       varchar(255),
    player_id            int8,
    username             varchar(255),
    fullname             varchar(255),
    player_image_url     varchar(255),
    highlight_id         int8,
    highlight_url        text,
    sport_image_url      text,
    highlight_image_url  text,
    talent_id            int4,
    igl_id               int4,
    streamer_id          int4,
    fan_fav_id           int4,
    coach_id             int4,
    pc_player_id         int4,
    mobile_player_id     int4,
    pc_team_id           int4,
    mobile_team_id       int4,
    fav_player_id        int4
);

-- Every nominee API route filters on slug (and usually sport_id).
CREATE INDEX idx_esn_awards_slug_sport ON esn.awards (slug, sport_id);


-- ---------------------------------------------------------------------
-- Votes
-- ---------------------------------------------------------------------
CREATE TABLE esn.submissions (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "timestamp"       timestamptz NOT NULL DEFAULT now(),
    email             varchar(255),
    phone_number      text,
    verified          boolean NOT NULL DEFAULT false,
    pc_team_id        int4,
    mobile_team_id    int4,
    pc_player_id      int4,
    mobile_player_id  int4,
    coach_id          int4,
    igl_id            int4,
    talent_id         int4,
    streamer_id       int4,
    fav_player_id     int4,
    highlight_id      int8 NOT NULL
);

CREATE TABLE esn.voters (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "identity"    varchar(255) NOT NULL,
    total         int4,
    last_updated  timestamptz NOT NULL DEFAULT now(),
    lmt           int4 DEFAULT 14,
    -- Calendar day of the vote in Ulaanbaatar time, independent of the
    -- session time zone. Used to enforce one vote per identity per day.
    vote_date     date GENERATED ALWAYS AS
                  ((last_updated AT TIME ZONE 'Asia/Ulaanbaatar')::date) STORED,
    CONSTRAINT uni_esn_voters_identity_day UNIQUE ("identity", vote_date)
);


-- ---------------------------------------------------------------------
-- Players, tournaments, achievements
-- ---------------------------------------------------------------------
CREATE TABLE esn.players (
    -- Same ids as esn.awards.player_id, so set explicitly on insert.
    id          int8 PRIMARY KEY,
    username    varchar(255) NOT NULL,
    fullname    varchar(255),
    image_url   varchar(255),
    sport_id    int8,
    created_at  timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE esn.tournaments (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         varchar(255) NOT NULL,
    sport_id     int8,
    event_month  date NOT NULL,
    created_at   timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT tournaments_event_month_first_day
        CHECK (EXTRACT(DAY FROM event_month) = 1),
    CONSTRAINT uni_esn_tournaments_name_month
        UNIQUE (name, event_month)
);

CREATE TABLE esn.achievements (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    player_id         int8 NOT NULL,
    tournament_id     int8 NOT NULL,
    achievement_type  varchar(32) NOT NULL,
    -- tournament_place: 1 = 1st place, 2 = 2nd place, ...
    -- mvp: always NULL
    placement         int2,
    created_at        timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT fk_esn_achievements_player
        FOREIGN KEY (player_id) REFERENCES esn.players(id),
    CONSTRAINT fk_esn_achievements_tournament
        FOREIGN KEY (tournament_id) REFERENCES esn.tournaments(id) ON DELETE CASCADE,
    CONSTRAINT achievements_type_check
        CHECK (achievement_type IN ('tournament_place', 'mvp')),
    CONSTRAINT achievements_placement_check
        CHECK (
            (achievement_type = 'tournament_place' AND placement > 0)
            OR
            (achievement_type = 'mvp' AND placement IS NULL)
        ),
    -- Also serves lookups by player_id (leading column).
    CONSTRAINT uni_esn_achievements_player_tournament_type
        UNIQUE (player_id, tournament_id, achievement_type)
);

CREATE INDEX idx_esn_achievements_tournament_id
    ON esn.achievements (tournament_id);

-- At most one MVP per tournament.
CREATE UNIQUE INDEX uni_esn_achievements_one_mvp_per_tournament
    ON esn.achievements (tournament_id)
    WHERE achievement_type = 'mvp';


-- ---------------------------------------------------------------------
-- News (not used by the voting app; author/users removed)
-- ---------------------------------------------------------------------
CREATE TABLE esn.categories (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at  timestamptz,
    updated_at  timestamptz,
    deleted_at  timestamptz,
    "name"      varchar(255) NOT NULL,
    CONSTRAINT uni_esn_categories_name UNIQUE ("name")
);
CREATE INDEX idx_esn_categories_deleted_at ON esn.categories (deleted_at);

CREATE TABLE esn.news (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at       timestamptz,
    updated_at       timestamptz,
    deleted_at       timestamptz,
    title            varchar(255) NOT NULL,
    slug             varchar(255) NOT NULL,
    image            varchar(255),
    publish_date     timestamptz NOT NULL,
    description      text NOT NULL,
    num_views        int8 NOT NULL DEFAULT 0,
    "content"        text NOT NULL,
    category_id      int8,
    minutes_to_read  int8 NOT NULL,
    CONSTRAINT uni_esn_news_slug UNIQUE (slug),
    CONSTRAINT fk_esn_news_category
        FOREIGN KEY (category_id) REFERENCES esn.categories(id)
);
CREATE INDEX idx_esn_news_deleted_at  ON esn.news (deleted_at);
CREATE INDEX idx_esn_news_category_id ON esn.news (category_id);


-- ---------------------------------------------------------------------
-- OTP service tables — only needed if the OTP service
-- (10.21.68.21/otp) is also repointed to Supabase.
-- ---------------------------------------------------------------------
CREATE TABLE esn.otp_configs (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    app_name        text NOT NULL,
    sms_text        text,
    email_subject   text,
    email_template  text,
    created_at      timestamptz,
    updated_at      timestamptz
);
CREATE UNIQUE INDEX idx_esn_otp_configs_app_name ON esn.otp_configs (app_name);

CREATE TABLE esn.otps (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    identifier     text NOT NULL,
    otp_hash       text NOT NULL,
    "type"         text NOT NULL,
    is_used        boolean DEFAULT false,
    is_active      boolean DEFAULT true,
    attempts       int8 DEFAULT 0,
    is_blocked     boolean DEFAULT false,
    blocked_until  timestamptz,
    expires_at     timestamptz NOT NULL,
    created_at     timestamptz,
    updated_at     timestamptz,
    deleted_at     timestamptz
);
CREATE INDEX idx_esn_otps_deleted_at ON esn.otps (deleted_at);
CREATE INDEX idx_esn_otps_identifier ON esn.otps (identifier);

CREATE TABLE esn.rate_limits (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    identifier  text NOT NULL,
    count       int8 DEFAULT 0,
    resets_at   timestamptz NOT NULL,
    created_at  timestamptz,
    updated_at  timestamptz
);
CREATE UNIQUE INDEX idx_esn_rate_limits_identifier ON esn.rate_limits (identifier);


-- ---------------------------------------------------------------------
-- Row Level Security: enabled with no policies, so the Supabase API
-- (anon / authenticated keys) can read or write nothing. The app's
-- direct `pg` connection uses the table owner and is not affected.
-- ---------------------------------------------------------------------
ALTER TABLE esn.awards        ENABLE ROW LEVEL SECURITY;
ALTER TABLE esn.submissions   ENABLE ROW LEVEL SECURITY;
ALTER TABLE esn.voters        ENABLE ROW LEVEL SECURITY;
ALTER TABLE esn.players       ENABLE ROW LEVEL SECURITY;
ALTER TABLE esn.tournaments   ENABLE ROW LEVEL SECURITY;
ALTER TABLE esn.achievements  ENABLE ROW LEVEL SECURITY;
ALTER TABLE esn.categories    ENABLE ROW LEVEL SECURITY;
ALTER TABLE esn.news          ENABLE ROW LEVEL SECURITY;
ALTER TABLE esn.otp_configs   ENABLE ROW LEVEL SECURITY;
ALTER TABLE esn.otps          ENABLE ROW LEVEL SECURITY;
ALTER TABLE esn.rate_limits   ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON ALL TABLES    IN SCHEMA esn FROM anon, authenticated;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA esn FROM anon, authenticated;


